param(
 [Parameter(Mandatory=$true)][string]$Repository,
 [string]$Tag='',
 [string]$ReleaseName='',
 [Parameter(Mandatory=$true)][string]$ArtifactDirectory,
 [switch]$Draft,
 [switch]$Prerelease,
 [switch]$DryRun
)
$ErrorActionPreference='Stop';Set-StrictMode -Version Latest
if($Repository-notmatch'^[^/\s]+/[^/\s]+$'){throw 'Repository must be owner/name'}
$ArtifactDirectory=[IO.Path]::GetFullPath($ArtifactDirectory);if(!(Test-Path $ArtifactDirectory -PathType Container)){throw 'ArtifactDirectory missing'}
$buildResultPath=Join-Path $ArtifactDirectory 'build-result.json'
if(Test-Path -LiteralPath $buildResultPath -PathType Leaf){$br=Get-Content -LiteralPath $buildResultPath -Raw -Encoding UTF8|ConvertFrom-Json;$v=[string]$br.ProductVersion;if([string]::IsNullOrWhiteSpace($v)){throw 'BUILD_RESULT_PRODUCT_VERSION_MISSING'};if([string]::IsNullOrWhiteSpace($Tag)){$Tag='v'+$v};if([string]::IsNullOrWhiteSpace($ReleaseName)){$ReleaseName='WordAgent '+$v};if($Tag-ne('v'+$v)){throw ('TAG_VERSION_MISMATCH expected=v'+$v+' actual='+$Tag)}}elseif([string]::IsNullOrWhiteSpace($Tag)-or[string]::IsNullOrWhiteSpace($ReleaseName)){throw 'TAG_AND_RELEASE_NAME_REQUIRED_WHEN_BUILD_RESULT_MISSING'}
$assets=@(Get-ChildItem $ArtifactDirectory -File|Where-Object{$_.Extension -in @('.zip','.exe','.json')}|Sort-Object Name);if($assets.Count-lt2){throw 'Release artifacts are incomplete'}
$gh=Get-Command gh.exe -ErrorAction SilentlyContinue
if($DryRun){Write-Host ('DRY_RUN=True');Write-Host ('REPOSITORY='+$Repository);Write-Host ('TAG='+$Tag);Write-Host ('ASSET_COUNT='+$assets.Count);Write-Host ('GH_AVAILABLE='+($null-ne$gh));exit 0}
if($null-eq$gh){throw 'gh.exe is required for GitHub release publishing'}
& $gh.Source auth status;if($LASTEXITCODE-ne0){throw 'gh auth status failed'}
$args=@('release','create',$Tag,'--repo',$Repository,'--title',$ReleaseName,'--notes','WordAgent release generated by the verified release toolchain.')
if($Draft){$args+='--draft'};if($Prerelease){$args+='--prerelease'};foreach($a in $assets){$args+=$a.FullName}
& $gh.Source @args;if($LASTEXITCODE-ne0){throw ('gh release create failed exit='+$LASTEXITCODE)}
